#!/usr/bin/env node
/*
 * Picks the best generated candidates (tools/puzzles/candidates.json) and writes
 * src/data/puzzles.js: three packs (win in 1, 2, 3) and a separate daily set.
 *
 *   node tools/puzzles/curate.js
 *
 * Rules for a good puzzle: one winning first move (two allowed in the warm-up),
 * a real finish (crack or Crown capture, not a round-limit decision), far from
 * the round limit, and enough pieces on the board to look like a game.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const R = require('../../src/rules.js');
const S = require('../../src/solver.js');
const AI = require('../../src/ai.js');

const all = require('./candidates.json').filter(p => (p.ends === 'stress' || p.ends === 'crown') && p.ply < 60);
const rng = AI.makeRng(20261101);
const shuffle = a => { for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(rng() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; } return a; };
const used = new Set();
const keyOf = p => p.rows.join('/') + p.stress.join(',');

function pick(filter, count, prefer) {
  const pool = shuffle(all.filter(p => !used.has(keyOf(p)) && filter(p)));
  pool.sort((a, b) => prefer(b) - prefer(a));
  const out = [];
  for (const p of pool) {
    if (out.length >= count) break;
    if (used.has(keyOf(p))) continue;
    // Re-prove with the solver: exact distance and the stored first move must still win.
    const st = R.fromRows(p.rows, { stress: p.stress, hits: p.hits, ply: p.ply });
    if (S.winDistance(st, p.n, 6e6) !== p.n) continue;
    if ((p.n > 1 && S.winDistance(st, p.n - 1, 6e6) !== 0)) continue;
    used.add(keyOf(p));
    out.push(p);
  }
  return out;
}

// Busier boards and Crown finishes make better puzzles; stress near the edge adds drama.
const interest = p => p.pieces * 2 + (p.ends === 'crown' ? 6 : 0) + (p.firsts === 1 ? 4 : 0) + Math.min(p.stress[1], 9) * 0.3 + rng();

const warm = pick(p => p.n === 1 && p.firsts <= 2 && p.pieces >= 3, 40, interest);
const tactics = pick(p => p.n === 2 && p.firsts === 1 && p.pieces >= 4, 60, interest);
const master = pick(p => p.n === 3 && p.firsts === 1 && p.pieces >= 4, 50, interest);
// Daily: mostly win in 2, some 1 and 3, interleaved so the week has a rhythm.
const d1 = pick(p => p.n === 1 && p.firsts === 1 && p.pieces >= 3, 20, interest);
const d2 = pick(p => p.n === 2 && p.firsts === 1 && p.pieces >= 4, 70, interest);
const d3 = pick(p => p.n === 3 && p.firsts === 1 && p.pieces >= 4, 30, interest);
const rhythm = [2, 2, 1, 3, 2, 2, 3];
const daily = [], dailyTotal = d1.length + d2.length + d3.length;
for (let i = 0; daily.length < dailyTotal; i++) {
  const want = rhythm[i % rhythm.length], src = want === 1 ? d1 : want === 2 ? d2 : d3;
  const fallback = [d2, d3, d1].find(a => a.length);
  daily.push((src.length ? src : fallback).shift());
}

const strip = (p, id) => ({ id, n: p.n, ends: p.ends, rows: p.rows, stress: p.stress, hits: p.hits, ply: p.ply, solution: p.solution });
const num = (i, w) => String(i + 1).padStart(w, '0');
const data = {
  packs: [
    { id: 'warmup', name: 'Warm-up', n: 1, blurb: 'Win in 1 move', puzzles: warm.map((p, i) => strip(p, 'w' + num(i, 2))) },
    { id: 'tactics', name: 'Tactics', n: 2, blurb: 'Win in 2 moves', puzzles: tactics.map((p, i) => strip(p, 't' + num(i, 2))) },
    { id: 'mastery', name: 'Mastery', n: 3, blurb: 'Win in 3 moves', puzzles: master.map((p, i) => strip(p, 'm' + num(i, 2))) }
  ],
  daily: daily.map((p, i) => strip(p, 'd' + num(i, 3)))
};

const file = path.join(__dirname, '../../src/data/puzzles.js');
fs.mkdirSync(path.dirname(file), { recursive: true });
fs.writeFileSync(file, '/* Generated by tools/puzzles/curate.js from engine-proven positions. Do not edit by hand. */\n' +
  '(function (root) {\n  const data = ' + JSON.stringify(data) + ';\n' +
  '  if (typeof module === \'object\' && module.exports) module.exports = data;\n  else root.StressPuzzles = data;\n' +
  '})(typeof self !== \'undefined\' ? self : this);\n');
console.log('packs:', data.packs.map(p => p.name + ' ' + p.puzzles.length).join(', '), '| daily:', data.daily.length,
  '| crown finishes:', [...warm, ...tactics, ...master, ...daily].filter(p => p.ends === 'crown').length, '->', file);
